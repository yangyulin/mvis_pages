import json
import re

import pytest

import make_fixtures as F
from mvis_site import assets
from mvis_site import site_files as S


def test_card_takes_its_own_name_and_maker_first():
    p = F.pub_entry("photo")
    assert S.card_for("rig", p) == {"title": "Rig", "href": "/sensors/rig/", "image": "/media/sensors/rig/rig.jpg", "alt": "The rig",
                                    "maker": "Maker Co", "type": "Stereo module", "tags": p["card"]["tags"]}
    p["card"]["maker"] = "Short"
    assert S.card_for("rig", p)["maker"] == "Short"
    q = F.pub_entry("old")
    assert S.card_for("o", q)["maker"] is None and S.card_for("o", q)["title"] == "Rig old"  # a maker without a link isn't named
    del q["header"]["maker"]
    assert S.card_for("o", q)["maker"] is None


def test_mdx_for_a_datasheet_and_an_older_page():
    m = S.mdx("rig", F.pub_entry("photo"))
    assert m.startswith('---\ntitle: "Rig photo"\ndescription: "A test rig."\npageType: example\nwide: true\nsensor: rig\n---\n')
    assert m.count("<SensorPage") == len(S.HEADER_PARTS) and 'part="lead"' not in m
    old = F.pub_entry("old")
    del old["header"]
    m = S.mdx("old", old)
    assert "sensor: old" not in m and m.count("<SensorPage") == len(S.PARTS) + 1 and 'part="lead"' in m


def test_sensor_pages_live_under_the_sensor_wiki():
    assert S.SENSOR_BASE == "/sensors/"
    assert "import SensorPage from '../../../components/SensorPage.astro';" in S.mdx("rig", F.pub_entry("photo"))
    text = S.overview_mdx(F.pub_doc())
    assert text.startswith("---\ntitle: Sensor wiki\n") and "import SensorGrid from '../../../components/SensorGrid.astro';" in text
    assert "](/benchmark/results/)" in text and "/benchmark/leaderboard/" not in text


def test_site_css_scopes_the_page_css():
    css = S.site_css(assets.page_css(), assets.header_css())
    assert css.startswith("/* Generated by export_sensor.py. */\n.sp{") and ".cards" not in css and "@media(max-width:1250px)" not in css
    assert assets.header_css() in css


def test_spot_rewrites_the_player_and_refuses_a_changed_one():
    js = S.spot(assets.progress_js())
    assert "SP_SPEED" in js and "' s of '" in js
    with pytest.raises(RuntimeError, match="update spot"):
        S.spot("changed player")


def test_site_js_wraps_player_and_map():
    js = S.site_js(assets.progress_js(), assets.page_js())
    assert js.startswith("// Generated by export_sensor.py") and js.endswith(S.FOLD_JS + "\n}\n") and assets.page_js() in js


def test_groups_follow_the_pub_order_and_drop_empty_groups():
    pub = F.pub_doc()
    assert S.sensor_groups(pub) == [{"title": "Group One", "slugs": ["rig-photo", "rig-groups"]}, {"title": "Group Two", "slugs": ["rig-old"]}]
    assert [n["link"] for n in S.sensor_nav(pub)] == ["/sensors/rig-photo/", "/sensors/rig-groups/", "/sensors/rig-old/"]


def test_sensor_without_a_known_group_fails():
    pub = F.pub_doc()
    pub["sensors"]["rig-old"]["group"] = "nope"
    with pytest.raises(ValueError, match="nope"):
        S.sensor_nav(pub)
    del pub["sensors"]["rig-old"]["group"]
    with pytest.raises(ValueError):
        S.sensor_groups(pub)


def test_overview_has_a_heading_per_group_and_every_sensor_once():
    pub = F.pub_doc()
    text = S.overview_mdx(pub)
    assert "[Group One](#group-one) · [Group Two](#group-two)" in text and "Empty" not in text
    for slug in pub["sensors"]:
        assert text.count(f'"{slug}"') == 1, slug


